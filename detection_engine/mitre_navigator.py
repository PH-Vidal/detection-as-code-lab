"""MITRE ATT&CK Navigator v4.5 layer exporter for Sigma rule coverage and active detections."""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from detection_engine.models import SEVERITY_ORDER, Alert, SigmaRule

SEVERITY_COLORS = {
    "critical": ("#dc2626", 100),
    "high": ("#f97316", 80),
    "medium": ("#eab308", 60),
    "low": ("#38bdf8", 40),
    "informational": ("#64748b", 30),
}
COVERAGE_ONLY_COLOR = "#0ea5e9"
COVERAGE_ONLY_SCORE = 25


def build_attack_navigator_layer(
    rules: list[SigmaRule],
    alerts: list[Alert] | None = None,
    *,
    layer_name: str = "Detection-as-Code Lab — MITRE ATT&CK Coverage & Detections",
) -> dict[str, Any]:
    """Build an ATT&CK Navigator v4.5 JSON dictionary from loaded rules and optional alerts."""
    rules_by_tech: dict[str, list[SigmaRule]] = defaultdict(list)
    for rule in rules:
        for tech in rule.mitre_techniques:
            rules_by_tech[tech.upper()].append(rule)

    alerts_by_tech: dict[str, list[Alert]] = defaultdict(list)
    for alert in alerts or []:
        for tech in alert.mitre_techniques:
            alerts_by_tech[tech.upper()].append(alert)

    sev_rank = {lvl: idx for idx, lvl in enumerate(SEVERITY_ORDER)}
    all_techniques = sorted(set(rules_by_tech) | set(alerts_by_tech))

    technique_entries: list[dict[str, Any]] = []
    for tech_id in all_techniques:
        linked_rules = rules_by_tech.get(tech_id, [])
        linked_alerts = alerts_by_tech.get(tech_id, [])

        if linked_alerts:
            top_sev = max(
                (a.severity.lower() for a in linked_alerts),
                key=lambda s: sev_rank.get(s, 0),
            )
            color, score = SEVERITY_COLORS.get(top_sev, ("#f97316", 80))
            comment_parts = [
                f"ACTIVE DETECTIONS ({len(linked_alerts)}, max severity: {top_sev.upper()}):",
                *[f"- [{a.severity.upper()}] {a.rule_title} (entity={a.entity})" for a in linked_alerts],
            ]
        else:
            color = COVERAGE_ONLY_COLOR
            score = COVERAGE_ONLY_SCORE
            comment_parts = ["Covered by Sigma rule(s) (no active alerts in this run):"]

        if linked_rules:
            comment_parts.append("Sigma Rules:")
            comment_parts.extend(f"- {r.title} ({r.playbook_id or 'N/A'})" for r in linked_rules)

        technique_entries.append(
            {
                "techniqueID": tech_id,
                "score": score,
                "color": color,
                "comment": "\n".join(comment_parts),
                "enabled": True,
                "showSubtechniques": "." in tech_id,
                "metadata": [
                    {"name": "sigma_rules", "value": str(len(linked_rules))},
                    {"name": "active_alerts", "value": str(len(linked_alerts))},
                ],
            }
        )

    return {
        "name": layer_name,
        "versions": {
            "attack": "15",
            "navigator": "4.9.1",
            "layer": "4.5",
        },
        "domain": "enterprise-attack",
        "description": (
            f"Generated by Detection-as-Code Lab from {len(rules)} Sigma rules "
            f"and {len(alerts or [])} triggered alert(s)."
        ),
        "sorting": 3,
        "layout": {
            "layout": "side",
            "aggregateFunction": "max",
            "showID": True,
            "showName": True,
            "showAggregateScores": True,
            "countUnscored": False,
        },
        "hideDisabled": False,
        "techniques": technique_entries,
        "gradient": {
            "colors": ["#0ea5e9", "#eab308", "#f97316", "#dc2626"],
            "minValue": 0,
            "maxValue": 100,
        },
        "legendItems": [
            {"label": "Covered by Sigma Rule (No Alert)", "color": COVERAGE_ONLY_COLOR},
            {"label": "Active Alert — Medium", "color": "#eab308"},
            {"label": "Active Alert — High", "color": "#f97316"},
            {"label": "Active Alert — Critical", "color": "#dc2626"},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#1e293b",
    }


def write_attack_navigator_layer(
    rules: list[SigmaRule],
    output_path: str | Path,
    *,
    alerts: list[Alert] | None = None,
) -> Path:
    """Export ATT&CK Navigator v4.5 layer JSON to disk."""
    layer = build_attack_navigator_layer(rules, alerts=alerts)
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(layer, indent=2), encoding="utf-8")
    return path
